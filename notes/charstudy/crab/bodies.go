// quarter height into quadrant glyphs, so each is 12 cells wide by 7 tall --
// the shipped cat's box, which a new companion is designed against.
//
// A crab is the first candidate that is WIDE where the cat is tall, so the box
// fills the other way round: the shell spans the full width and the height is
// spent on claws and legs rather than on a head. Everything below is aligned to
// the cell rows (px 0-3, 4-7, 8-11, 12-15, 16-19, 20-23, 24-27) -- a feature
// that straddles two of them merges into a bar when it is halved.
